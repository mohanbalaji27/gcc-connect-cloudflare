/** Shuffles tips deterministically for the day or randomly across sessions. */
export function getDailyTip() {
  const dayIndex = Math.floor(Date.now() / 86_400_000);
  return OFFICE_TIPS[Math.abs(dayIndex) % OFFICE_TIPS.length];
}

/** Returns a random tip that is different on each call. */
export function getRandomTip() {
  const index = Math.floor(Math.random() * OFFICE_TIPS.length);
  return OFFICE_TIPS[index];
}

/** Hook for Login screen tips. */
export function getLoginTip() {
  return getRandomTip();
}
