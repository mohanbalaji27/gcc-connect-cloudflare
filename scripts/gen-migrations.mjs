// Generates worker/migrations.generated.js: the Worker cannot read the file system, so every migration file is imported
// (as text) into one list. Run automatically by `npm run cf:dev` and `npm run cf:deploy`; a test fails if the committed
// file is out of date, so a new server/migrations/NNN-*.sql can never be forgotten.
import { readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DIRECTORY = new URL('../server/migrations/', import.meta.url);
const OUTPUT = new URL('../worker/migrations.generated.js', import.meta.url);

export const migrationFileNames = () => readdirSync(DIRECTORY).filter((name) => /^\d{3}-.+\.sql$/.test(name)).sort();

export function renderMigrationsModule(names) {
  const identifiers = names.map((name) => `m${name.slice(0, 3)}`);
  return [
    '// GENERATED by scripts/gen-migrations.mjs from server/migrations/*.sql. Do not edit by hand; run `npm run migrations:gen`.',
    ...names.map((name, index) => `import ${identifiers[index]} from '../server/migrations/${name}';`),
    '',
    'export const MIGRATIONS = [',
    ...names.map((name, index) => `  { version: ${Number(name.slice(0, 3))}, sql: ${identifiers[index]} },`),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, renderMigrationsModule(migrationFileNames()));
  console.log(`Wrote worker/migrations.generated.js (${migrationFileNames().length} migrations).`);
}
